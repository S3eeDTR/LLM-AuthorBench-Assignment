"""Read the inspected JSON schema; never execute dataset programs."""
import json,zipfile,hashlib,shutil,urllib.request,datetime,re
import pandas as pd
from .utils import ROOT,save_json,digest
URL='https://github.com/LLMauthorbench/LLMauthorbench'
COMMIT='6a1c2ac173c774cfbd012f4c81e8d0a51bb61eb7'
ARCHIVE_SHA256='e24399b7b05b812c5a1148ef44245348859eaa74b1140523cb695f984337f24c'
def inspect():
    archive=ROOT/'data/raw/LLM-AuthorBench.json.zip'
    if not archive.exists():
        supplied=ROOT/'LLM-AuthorBench.json.zip'
        if supplied.exists(): shutil.copy2(supplied,archive)
        else: urllib.request.urlretrieve(URL.replace('github.com','raw.githubusercontent.com')+f'/{COMMIT}/LLM-AuthorBench.json.zip',archive)
    if hashlib.sha256(archive.read_bytes()).hexdigest()!=ARCHIVE_SHA256:
        raise ValueError('Archive differs from the verified experiment version; inspect before proceeding.')
    with zipfile.ZipFile(archive) as z:
        records=json.loads(z.read('LLM-AuthorBench.json'))
    valid=[]; malformed=[]
    for i,r in enumerate(records):
        if not isinstance(r,dict) or any(not isinstance(r.get(k),str) or not r[k].strip() for k in ('model_name','prompt','c_code')):
            malformed.append(i); continue
        valid.append(dict(row_id=i,label=r['model_name'],prompt=r['prompt'],code=r['c_code'],source_hash=digest(r['c_code'])))
    df=pd.DataFrame(valid)
    duplicates=df.duplicated('source_hash').sum()
    cross=(df.groupby('source_hash').label.nunique()>1).sum()
    stats={'total_records':len(records),'valid_programs':len(df),'classes':df.label.nunique(),'exact_prompts':df.prompt.nunique(),'malformed_or_missing_or_empty':len(malformed),'exact_duplicate_excess':int(duplicates),'cross_label_duplicate_hashes':int(cross),'empty_code':sum(isinstance(r,dict) and isinstance(r.get('c_code'),str) and not r['c_code'].strip() for r in records),'missing_required_fields':sum(not isinstance(r,dict) or any(k not in r or r[k] is None for k in ('model_name','prompt','c_code')) for r in records),'archive_sha256':hashlib.sha256(archive.read_bytes()).hexdigest(),'source':URL,'license':'No license file or explicit dataset license found in inspected upstream repository; redistribution permission unverified','inspection_utc':datetime.datetime.now(datetime.timezone.utc).isoformat(),'original_download_date':'Unknown: user-supplied archive','available_fields':list(records[0]),'problem_identifier':'No explicit task ID; prompt-derived conservative task families'}
    commit=ROOT/'data/raw/upstream_commit.json'
    if commit.exists(): stats['upstream_reference_commit']=json.loads(commit.read_text(encoding='utf-8-sig'))['sha']
    stats['upstream_reference_commit']=COMMIT
    stats['archive_matches_upstream_commit']=True
    stats['missing_values_by_field']={k:sum(not isinstance(r,dict) or r.get(k) is None for r in records) for k in records[0]}
    stats['stored_checksum_mismatches']=sum(r.get('SHA256_checksum')!=digest(r['c_code']) for r in records if isinstance(r,dict) and isinstance(r.get('c_code'),str))
    stats['class_counts']=df.label.value_counts().sort_index().to_dict()
    pd.DataFrame([{'statistic':k,'value':json.dumps(v) if isinstance(v,(dict,list)) else v} for k,v in stats.items()]).to_csv(ROOT/'results/dataset_statistics.csv',index=False)
    save_json('results/dataset_statistics.json',stats)
    pd.DataFrame({'row_id':malformed}).to_csv(ROOT/'results/excluded_records.csv',index=False)
    # Exact duplicate copies are removed within labels; conflicting labels are excluded.
    conflicts=df.groupby('source_hash').label.nunique(); df=df[~df.source_hash.isin(conflicts[conflicts>1].index)].drop_duplicates('source_hash').copy()
    pattern=re.compile(r'claude|gpt[- _]?4|gemini|qwen|deepseek|llama|generated by|author\s*:|problem[_ -]?id',re.I)
    hits=[dict(row_id=r.row_id,label=r.label,term=m.group(),context=r.code[max(0,m.start()-70):m.end()+90]) for r in df.itertuples() for m in pattern.finditer(r.code)]
    pd.DataFrame(hits,columns=['row_id','label','term','context']).to_csv(ROOT/'results/source_leakage_audit.csv',index=False)
    print(f'Inspected {len(records):,} records; {df.label.nunique()} classes; {df.prompt.nunique():,} exact prompts.',flush=True)
    print(df.label.value_counts().to_string(),flush=True)
    return df,stats
